/**
 * Heuristic generator for any satellite not explicitly in the known dossiers table
 */
export function getSatelliteDossier(
  id: string,
  name: string,
  category: string,
  intlDesig?: string,
  launchYear?: number
): SatelliteDossier {
  // Check exact NORAD ID match first
  if (KNOWN_SATELLITE_DOSSIERS[id]) {
    return KNOWN_SATELLITE_DOSSIERS[id];
  }

  const upper = name.toUpperCase();

  // 1. Starlink Constellation
  if (upper.includes('STARLINK') || category === 'starlink') {
    const year = launchYear || 2023;
    const isDirectToCell = upper.includes('DIRECT') || upper.includes('CELL');
    const isV2 = upper.includes('V2') || parseInt(id, 10) > 55000;

    return {
      country: 'США',
      countryFlag: '🇺🇸',
      countryCode: 'US',
      operator: 'SpaceX (Илон Маск)',
      launchDate: `${year} год`,
      launchSite: 'Мыс Канаверал (SLC-40) или Ванденберг (SLC-4E), США',
      rocket: 'Falcon 9 Block 5',
      purpose: 'Глобальный широкополосный спутниковый интернет',
      summary: `Спутник группировки Starlink ${isV2 ? 'поколения V2 Mini' : 'поколения v1.5'} компании SpaceX. Оснащен фазированной антенной решеткой Ku/Ka-диапазона, лазерной межспутниковой связью и криптоновыми/аргоновыми ионными двигателями Холла для удержания орбиты и безопасного свода с орбиты в конце срока службы.`,
      funFact: isDirectToCell
        ? 'Оснащен сотовым ретранслятором Direct to Cell для прямой связи с обычными смартфонами 4G LTE без модификаций!'
        : 'Спутник весит около 300–800 кг и в конце срока службы полностью сгорает в плотных слоях атмосферы без образования космического мусора.'
    };
  }

  // 2. Russian Spacecraft (ГЛОНАСС, Космос, Метеор, Ресурс, Союз, Прогресс)
  if (
    upper.includes('ГЛОНАСС') ||
    upper.includes('GLONASS') ||
    upper.includes('COSMOS') ||
    upper.includes('КОСМОС') ||
    upper.includes('METEOR') ||
    upper.includes('МЕТЕОР') ||
    upper.includes('LUCH') ||
    upper.includes('ЛУЧ') ||
    upper.includes('RESURS') ||
    upper.includes('ELEKTRO')
  ) {
    const year = launchYear || 2018;
    return {
      country: 'Россия',
      countryFlag: '🇷🇺',
      countryCode: 'RU',
      operator: 'Роскосмос / ВКС РФ',
      launchDate: `${year} год`,
      launchSite: 'Космодром Плесецк / Байконур / Восточный',
      rocket: 'Союз-2.1б или Протон-М',
      purpose: category === 'navigation' ? 'Глобальная спутниковая навигация ГЛОНАСС' : 'Государственный спутниковый мониторинг и связь',
      summary: `Российский космический аппарат «${name}». Спроектирован и изготовлен ведущими предприятиями ракетно-космической отрасли России (РКЦ «Прогресс», АО «ИСС» им. Решетнёва или ВНИИЭМ) для решения государственных, оборонных и народнохозяйственных задач.`,
      funFact: 'Запущен с одного из ключевых космодромов и находится под постоянным контролем Главного испытательного космического центра им. Г.С. Титова.'
    };
  }

  // 3. European Space Agency (Galileo, Sentinel, MetOp, Envisat, Cryosat)
  if (
    upper.includes('GALILEO') ||
    upper.includes('SENTINEL') ||
    upper.includes('METOP') ||
    upper.includes('CRYOSAT') ||
    upper.includes('CHEOPS') ||
    upper.includes('SMOS')
  ) {
    const year = launchYear || 2019;
    return {
      country: 'Европейский союз',
      countryFlag: '🇪🇺',
      countryCode: 'EU',
      operator: 'ESA (Европейское космическое агентство)',
      launchDate: `${year} год`,
      launchSite: 'Гвианский космический центр (Куру), Французская Гвиана',
      rocket: 'Vega / Ariane / Falcon 9',
      purpose: category === 'weather' ? 'Дистанционное зондирование Земли и климат' : 'Гражданская спутниковая навигация и наука',
      summary: `Европейский космический аппарат «${name}» программы Европейского союза и агентства ESA. Оснащен высокоточной оптической и радарной аппаратурой для непрерывного гражданского мониторинга планеты и обеспечения навигации.`,
      funFact: 'Все научные данные с европейских гражданских спутников открыто публикуются для мирового научного сообщества.'
  };
  }

  // 4. Chinese Spacecraft (Tiangong, Beidou, Chang'e, Gaofen, Yaogan, Shenzhou)
  if (
    upper.includes('BEIDOU') ||
    upper.includes('TIANGONG') ||
    upper.includes('YAOGAN') ||
    upper.includes('GAOFEN') ||
    upper.includes('SHENZHOU') ||
    upper.includes('FENGYUN') ||
    upper.includes('TIANZHOU')
  ) {
    const year = launchYear || 2021;
    return {
      country: 'Китай',
      countryFlag: '🇨🇳',
      countryCode: 'CN',
      operator: 'CNSA (Китайское национальное космическое управление)',
      launchDate: `${year} год`,
      launchSite: 'Космодромы Вэньчан / Цзюцюань / Сичан / Тайюань',
      rocket: 'Семейство ракет-носителей «Чанчжэн» (Long March)',
      purpose: category === 'navigation' ? 'Китайская глобальная навигационная система Бэйдоу (BDS)' : 'Орбитальная инфраструктура и дистанционное зондирование',
      summary: `Космический аппарат «${name}» космической программы Китайской Народной Республики. Является частью масштабной национальной программы освоения околоземного пространства и создания независимой космической инфраструктуры.`,
      funFact: 'Китайские запуски ракет серии «Чанчжэн» проводятся регулярно с четырех современных государственных космодромов.'
    };
  }

  // 5. General NASA / US (GPS, NOAA, GOES, Landsat, Hubble, Explorer)
  if (
    upper.includes('GPS') ||
    upper.includes('NAVSTAR') ||
    upper.includes('NOAA') ||
    upper.includes('GOES') ||
    upper.includes('LANDSAT') ||
    upper.includes('USA') ||
    upper.includes('CYGNUS')
  ) {
    const year = launchYear || 2016;
    return {
      country: 'США',
      countryFlag: '🇺🇸',
      countryCode: 'US',
      operator: category === 'navigation' ? 'US Space Force' : 'NASA / NOAA',
      launchDate: `${year} год`,
      launchSite: 'Мыс Канаверал (Флорида) или База Ванденберг (Калифорния)',
      rocket: 'Falcon 9 / Atlas V / Delta IV',
      purpose: category === 'navigation' ? 'Спутниковая навигация GPS' : 'Метеонаблюдения и научные исследования',
      summary: `Американский спутник «${name}». Разработан по государственному заказу США ведущими аэрокосмическими корпорациями (Lockheed Martin, Boeing, Northrop Grumman) для круглосуточного обеспечения глобальной безопасности, науки или метеопрогнозов.`,
      funFact: 'Спутник передает радиосигналы на международных частотах, принимаемые наземными станциями по всему миру.'
    };
  }

  // Generic fallback based on parsed launch year and category
  const year = launchYear || 2020;
  return {
    country: 'Международный / Национальные космические агентства',
    countryFlag: '🛰️',
    countryCode: 'INT',
    operator: 'Официальный космический оператор',
    launchDate: `${year} год`,
    launchSite: 'Государственный космодром',
    purpose: category === 'stations'
      ? 'Пилотируемый полет и орбитальные исследования'
      : category === 'navigation'
      ? 'Спутниковое позиционирование и время'
      : category === 'weather'
      ? 'Метеорология и наблюдение Земли'
      : category === 'science'
      ? 'Фундаментальные астрономические исследования'
      : 'Околоземная телекоммуникация и ретрансляция',
    summary: `Космический аппарат «${name}» (каталожный номер NORAD ${id}). Находится на стабильной околоземной орбите и выполняет запланированные задачи в интересах международного сообщества или национальной космической программы.`,
    funFact: `Орбитальные параметры обновляются баллистическими центрами NORAD и CelesTrak каждые несколько часов.`
  };
}
